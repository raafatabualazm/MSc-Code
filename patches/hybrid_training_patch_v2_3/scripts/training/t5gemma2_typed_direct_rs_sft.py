#!/usr/bin/env python3
"""Typed-contract, direct-only RS-SFT over sealed verified targets.

This profile deliberately does not reinterpret the historical evidence.  It
first validates each local/API report with the original mixed-RS-SFT validators
and their original untyped F2 hashes.  Only after that validation succeeds does
it rebind the verified Dart target to the byte-identical opaque typed-contract
source used by the fresh typed SFT arm.

The training schedule contains direct rows only: no gold replay, no local/API
repair-conditioned prefix, no tests, and no private feedback.  Every rebound
target is also re-executed against the task's complete TRAIN acceptance suite;
only the binary outcome and hashes are retained.
"""

